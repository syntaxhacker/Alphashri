/**
 * Typography tier (dark-only).
 *
 * One six-step type scale for the product. Components use the Tailwind
 * `text-ui-*` utilities generated from these tokens; chart/canvas consumers
 * read the same sizes from `uiTheme.fontSizes` or `TYPE_SCALE`. No component
 * should paint a private pixel size.
 *
 * The floor is 12px: the report's legibility audit (2026-11-23) raised dense
 * axis/table text off 11px and this is the shared contract from now on.
 */
export const TYPE_SCALE = {
  /** Dense labels, badges, chart axes. The hard floor. */
  micro: { size: 12, lineHeight: 16 },
  /** Dense body copy and table cells. */
  body: { size: 13, lineHeight: 18 },
  /** Form labels and controls. */
  label: { size: 14, lineHeight: 20 },
  /** Card/panel titles. */
  title: { size: 16, lineHeight: 24 },
  /** Page-section headings. */
  heading: { size: 20, lineHeight: 28 },
  /** Page titles / hero values. */
  display: { size: 24, lineHeight: 32 },
} as const;

export type TypeRole = keyof typeof TYPE_SCALE;

/** Tailwind utility per role; generated by the `--text-ui-*` theme tokens. */
export const TYPE_CLASS = {
  micro: "text-ui-micro",
  body: "text-ui-body",
  label: "text-ui-label",
  title: "text-ui-title",
  heading: "text-ui-heading",
  display: "text-ui-display",
} as const satisfies Record<TypeRole, string>;

/** The token name behind a role, e.g. `--text-ui-body`. */
export function typeToken(role: TypeRole): `--text-ui-${TypeRole}` {
  return `--text-ui-${role}`;
}

/** Pixel size for a role, for SVG/chart code that cannot use a class. */
export function typeSize(role: TypeRole): number {
  return TYPE_SCALE[role].size;
}

/** CSS for an inline-styled node that must stay on the scale. */
export function typeStyle(role: TypeRole): {
  "font-size": string;
  "line-height": string;
} {
  return {
    "font-size": `${TYPE_SCALE[role].size}px`,
    "line-height": `${TYPE_SCALE[role].lineHeight}px`,
  };
}
