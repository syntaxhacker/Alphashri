"""Generate src/api/valuePresets.generated.ts from api/value_scan/presets.json.

Deterministic: output depends only on the checked-in JSON, never on the clock,
environment or filesystem order. Run from the repo root:

    .venv/bin/python scripts/gen_value_presets.py
    .venv/bin/python scripts/gen_value_presets.py --out /tmp/valuePresets.generated.ts

The second form is used by the drift test to byte-compare a fresh render with
the checked-in artifact.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "api/value_scan/presets.json"
DEFAULT_OUT = REPO_ROOT / "src/api/valuePresets.generated.ts"


def _string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _gate_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return _string(value)
    raise TypeError(f"unsupported preset gate value: {value!r}")


def render(specs: dict[str, dict]) -> str:
    ids = list(specs)
    lines = [
        "// AUTO-GENERATED by scripts/gen_value_presets.py from api/value_scan/presets.json.",
        "// Do not edit by hand — regenerate: .venv/bin/python scripts/gen_value_presets.py",
        "",
        "export type ValuePresetName =",
    ]
    for index, preset_id in enumerate(ids):
        terminator = ";" if index == len(ids) - 1 else ""
        lines.append(f'  | "{preset_id}"{terminator}')
    lines += [
        "",
        "export const PRESET_IDS: readonly ValuePresetName[] = [",
        *[f'  "{preset_id}",' for preset_id in ids],
        "];",
        "",
        "export interface ValuePreset {",
        "  label: string;",
        "  description: string;",
        "  gates: Record<string, string | number | boolean>;",
        "}",
        "",
        "export const VALUE_PRESETS: Record<string, ValuePreset> = {",
    ]
    for preset_id, spec in specs.items():
        lines += [
            f'  "{preset_id}": {{',
            f"    label: {_string(spec['label'])},",
            f"    description: {_string(spec['description'])},",
        ]
        if spec["gates"]:
            lines.append("    gates: {")
            lines += [
                f"      {_string(key)}: {_gate_value(value)},"
                for key, value in spec["gates"].items()
            ]
            lines.append("    },")
        else:
            lines.append("    gates: {},")
        lines.append("  },")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output TS path")
    args = parser.parse_args()
    specs = json.loads(SOURCE.read_text(encoding="utf-8"))
    args.out.write_text(render(specs), encoding="utf-8")


if __name__ == "__main__":
    main()
